package com.tnsif.intro;

public class Relational {
	public static void main(String [] args)
	{
		int a=7;
		int b=9;
		boolean c;
		c = a < b;
		System.out.println(c);
		c = a > b;
		System.out.println(c);
		c = a <= b;
		System.out.println(c);
		c = a >= b;
		System.out.println(c);
		c = a != b;
		System.out.println(c);
		c = a == b;
		System.out.println(c);
	}

}
